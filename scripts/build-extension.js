/**
 * scripts/build-extension.js
 *
 * 将 shared/inject/*.js 的 export 打包为 extension/content/inject-scripts.js
 *
 * shared/inject/ 中的脚本使用 ES export，Web 插件无法直接 import。
 * 此脚本提取所有 export 定义，写入 window.__CX_INJECT 对象，
 * content script 通过读取该对象来注入脚本。
 *
 * 用法:
 *   node scripts/build-extension.js
 */

import { readFileSync, writeFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const sharedDir = resolve(__dirname, "../shared/inject");
const outFile = resolve(__dirname, "../extension/content/inject-scripts.js");
const popupScriptsFile = resolve(__dirname, "../extension/popup/popup-scripts.js");

const modules = ["discover", "chapters", "video-control", "document", "task-complete", "task-runner"];

const scripts = {};

for (const name of modules) {
  const filePath = resolve(sharedDir, `${name}.js`);
  const content = readFileSync(filePath, "utf-8");

  // 提取: export const NAME = `...`;
  const constRe = /export\s+const\s+(\w+)\s*=\s*`([\s\S]*?)`;/g;
  let match;
  while ((match = constRe.exec(content)) !== null) {
    scripts[match[1]] = match[2];
  }

  // 提取: export function NAME(arg) { return `...`; }
  // 用贪婪匹配找到完整的函数体
  const funcRe = /export\s+function\s+(\w+)\s*\(([^)]*)\)\s*\{[\s\S]*?return\s+`([\s\S]*?)\`[\s\S]*?\n\}/g;
  while ((match = funcRe.exec(content)) !== null) {
    scripts[match[1]] = {
      __type: "function",
      template: match[3],
      params: match[2].trim(),
    };
  }
}

const output = `// Auto-generated by scripts/build-extension.js — DO NOT EDIT
// Provides shared/inject/ scripts to content scripts
window.__CX_INJECT = ${JSON.stringify(scripts, null, 2)};
`;

writeFileSync(outFile, output);
console.log(`✅ Built: ${outFile}`);
console.log(`   ${Object.keys(scripts).length} scripts extracted`);

// ---- 同步 manifest.json 版本号 ----
const pkgPath = resolve(__dirname, "../package.json");
const pkg = JSON.parse(readFileSync(pkgPath, "utf-8"));
const manifestPath = resolve(__dirname, "../extension/manifest.json");
const manifest = JSON.parse(readFileSync(manifestPath, "utf-8"));
if (manifest.version !== pkg.version) {
  manifest.version = pkg.version;
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
  console.log(`🔖 manifest.json version synced: ${manifest.version} → ${pkg.version}`);
} else {
  console.log(`🔖 manifest.json version: ${manifest.version}`);
}

// ---- 生成 popup 可引用的脚本文件 ----
const popupLines = ["// Auto-generated by scripts/build-extension.js — DO NOT EDIT"];
popupLines.push("// Scripts for popup.js to inject via chrome.scripting.executeScript");
popupLines.push("const SCRIPTS = {");

const entries = Object.entries(scripts);
for (let i = 0; i < entries.length; i++) {
  const [key, value] = entries[i];
  const comma = i < entries.length - 1 ? "," : "";
  if (typeof value === "string") {
    popupLines.push(`  "${key}": ${JSON.stringify(value)}${comma}`);
  } else if (value && value.__type === "function") {
    popupLines.push(`  "${key}": ${JSON.stringify(value)}${comma}`);
  }
}
popupLines.push("};");

writeFileSync(popupScriptsFile, popupLines.join("\n") + "\n");
console.log(`✅ Built: ${popupScriptsFile}`);
